    private void jButtonPokreniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPokreniActionPerformed
        jButtonPokreni.setEnabled(false);
        pokrenut = true;
        jButtonOdg1.setEnabled(true);
        jButtonOdg2.setEnabled(true);
        jButtonOdg3.setEnabled(true);
        jButtonSlPitanje.setEnabled(true);

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.VRATI_PITANJA, null);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        listaPitanja = (List<Pitanje>) so.getOdgovor();

        Pitanje prvoPitanje = listaPitanja.get(rb);

        brojSekundi = prvoPitanje.getBrojSekundi();

        thread = new Thread(this);
        pokreniTajmer();
        thread.start();

        jLabelPitanje.setText(++rb + ". " + prvoPitanje.getTekst());
        jLabelOdg1.setText(prvoPitanje.getOdgovori().get(0).getTekst());
        jLabelOdg2.setText(prvoPitanje.getOdgovori().get(1).getTekst());
        jLabelOdg3.setText(prvoPitanje.getOdgovori().get(2).getTekst());
        jButtonOdg1.setEnabled(true);
        jButtonOdg2.setEnabled(true);
        jButtonOdg3.setEnabled(true);
        jButtonSlPitanje.setEnabled(true);

        jLabelTacniOdgovori.setText("Tacni odgovori: " + tacniOdgovori);
        jLabelNetacniOdgovori.setText("Netacni odgovori: " + netacniOdgovori);
        jLabelPreskoceniOdgovori.setText("Preskoceni odgovori: " + preskoceniOdgovori);
        jLabelBrojPoena.setText("Broj poena: " + brojPoena);

        //ovo pozivamo da bi na sf formi ispisali da je pokrenut kviz
        pokreniKviz();

    }//GEN-LAST:event_jButtonPokreniActionPerformed

