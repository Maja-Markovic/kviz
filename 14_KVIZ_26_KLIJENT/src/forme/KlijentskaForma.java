    @Override
    public void run() {

        jLabelTajmer.setText("Preostalo sekundi: " + brojSekundi);
        while (aktivanTajmer) {
            try {
                Thread.sleep(2000);
            } catch (InterruptedException ex) {
                Logger.getLogger(KlijentskaForma.class.getName()).log(Level.SEVERE, null, ex);
            }

            jLabelTajmer.setText("Preostalo sekundi: " + (--brojSekundi));

            if (brojSekundi == 0) {

                if (rb == 5) {
                    zaustaviTajmer();
                    azurirajRbPitanjaBrPoenaNaSFFormi();
                    zaustaviKviz();
                    return;
                }

                azurirajRbPitanjaBrPoenaNaSFFormi();

                JOptionPane.showMessageDialog(this, "ISTEKLO JE VREME!");

                Pitanje sledecePitanje = listaPitanja.get(rb);

                brojSekundi = sledecePitanje.getBrojSekundi();
                jLabelTajmer.setText("Preostalo sekundi: " + brojSekundi);

                jLabelPitanje.setText(++rb + ". " + sledecePitanje.getTekst());
                jLabelOdg1.setText(sledecePitanje.getOdgovori().get(0).getTekst());
                jLabelOdg2.setText(sledecePitanje.getOdgovori().get(1).getTekst());
                jLabelOdg3.setText(sledecePitanje.getOdgovori().get(2).getTekst());
                jLabelOdg1.setBackground(null);
                jLabelOdg2.setBackground(null);
                jLabelOdg3.setBackground(null);
                preskoceniOdgovori++;
                jLabelPreskoceniOdgovori.setText("Preskoceni odgovori: " + preskoceniOdgovori);

            }
        }
    }

    private void pokreniTajmer() {
        aktivanTajmer = true;
    }

    private void zaustaviTajmer() {
        aktivanTajmer = false;
    }

    private void zaustaviKviz() {
        JOptionPane.showMessageDialog(this, "KVIZ JE ZAVRSEN. MOZETE SE ODJAVITI SA SISTEMA.");
        pokrenut = false;
        zavrsen = true;
        jLabelTajmer.setText("Preostalo sekundi: ");
        jLabelOdg1.setBackground(null);
        jLabelOdg2.setBackground(null);
        jLabelOdg3.setBackground(null);
        jButtonOdg1.setEnabled(false);
        jButtonOdg2.setEnabled(false);
        jButtonOdg3.setEnabled(false);
        jButtonSlPitanje.setEnabled(false);
        azurirajRbPitanjaBrPoenaNaSFFormi();
    }

    private void azurirajRbPitanjaBrPoenaNaSFFormi() {
        ulogovani.setRbPitanja(rb);
        ulogovani.setPokrenutKviz(pokrenut);
        ulogovani.setBrojPoena(brojPoena);

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.AZURIRAJ, ulogovani);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean azuriraj = (boolean) so.getOdgovor();

        if (azuriraj) {
            JOptionPane.showMessageDialog(this, "USPESNO AZURIRANO");
        } else {
            JOptionPane.showMessageDialog(this, "NEUSPESNO AZURIRANO");
        }

    }

    private void azurirajTacan() {
        tacniOdgovori++;
        brojPoena += 4;
        jLabelTacniOdgovori.setText("Tacni odgovori: " + tacniOdgovori);
        jLabelBrojPoena.setText("Broj poena: " + brojPoena);
    }

    private void azurirajNetacan() {
        netacniOdgovori++;
        brojPoena -= 2;
        if (brojPoena < 0) {
            brojPoena = 0;
        }
        jLabelNetacniOdgovori.setText("Netacni odgovori: " + netacniOdgovori);
        jLabelBrojPoena.setText("Broj poena: " + brojPoena);
    }

    private void sledecePitanje() {
        JOptionPane.showMessageDialog(this, "SLEDECE PITANJE!");

        Pitanje sledecePitanje = listaPitanja.get(rb);

        brojSekundi = sledecePitanje.getBrojSekundi();
        jLabelTajmer.setText("Preostalo sekundi: " + brojSekundi);

        jLabelPitanje.setText(++rb + ". " + sledecePitanje.getTekst());
        jLabelOdg1.setText(sledecePitanje.getOdgovori().get(0).getTekst());
        jLabelOdg2.setText(sledecePitanje.getOdgovori().get(1).getTekst());
        jLabelOdg3.setText(sledecePitanje.getOdgovori().get(2).getTekst());
        jLabelOdg1.setBackground(null);
        jLabelOdg2.setBackground(null);
        jLabelOdg3.setBackground(null);
        thread = new Thread(this);
        pokreniTajmer();
        thread.start();
    }

    private void pokreniKviz() {
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.POKRENI_KVIZ, ulogovani);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean pokrenutKviz = (boolean) so.getOdgovor();

        if (pokrenutKviz) {
            JOptionPane.showMessageDialog(this, "USPESNO POKRENUT");
        } else {
            JOptionPane.showMessageDialog(this, "DOSLO JE DO GRESKE U POKRETANJU KVIZA");
        }
    }

