    private void jButtonLogoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLogoutActionPerformed
        if (pokrenut && !zavrsen) {
            JOptionPane.showMessageDialog(this, "NE MOZETE SE ODJAVITI");
            return;
        }

        int result = JOptionPane.showConfirmDialog(this, "DA LI ZELITE DA SE ODJAVITE?", "KONFIRMACIJA", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.LOGOUT, ulogovani);
            Komunikacija.getInstance().posaljiZahtev(kz);

            ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
            boolean uspeh = (boolean) so.getOdgovor();

            if (uspeh) {
                JOptionPane.showMessageDialog(this, "USPESNO STE SE ODJAVILI");
                System.exit(0);
            } else {
                JOptionPane.showMessageDialog(this, "GRESKA PRI ODJAVI");
            }
        }


    }//GEN-LAST:event_jButtonLogoutActionPerformed

