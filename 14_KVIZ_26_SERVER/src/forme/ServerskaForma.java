    private void jButtonPokreniServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPokreniServerActionPerformed
        
        if (jTextFieldMAX.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "MORATE UNETI BROJ");
            return;
        }
        
        int maxBrKlijenata = Integer.parseInt(jTextFieldMAX.getText());

        if (maxBrKlijenata < 0) {
            JOptionPane.showMessageDialog(this, "MORATE UNETI BROJ VECI OD 0");
            return;
        }
        
        Controller.getInstance().setMaxBrKlijenata(maxBrKlijenata);
        PokreniServer ps = new PokreniServer();
        ps.start();


    }//GEN-LAST:event_jButtonPokreniServerActionPerformed

